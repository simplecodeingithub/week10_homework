if __name__ == "__main__":
    # Start the Flask development server
    # debug=True enables:
    # - Automatic reloading when code changes
    # - Detailed error pages
    # - Debug console for errors
    # NOTE: debug=True should NOT be used in production environments
    app.run(debug=True)